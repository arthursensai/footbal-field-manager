create table if not exists public.field_settings (
  id boolean primary key default true check (id),
  opening_time time not null default time '08:00',
  closing_time time not null default time '21:00',
  timezone text not null default 'Africa/Casablanca',
  currency text not null default 'MAD',
  updated_at timestamptz not null default now(),
  constraint valid_opening_hours check (opening_time < closing_time or closing_time = time '00:00')
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  customer_name text not null check (length(trim(customer_name)) between 2 and 120),
  phone text check (phone is null or length(trim(phone)) between 6 and 20),
  start_time timestamptz not null,
  end_time timestamptz not null,
  status text not null default 'confirmed' check (status in ('confirmed','cancelled')),
  created_by uuid references public.profiles(id) on delete set null,
  updated_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint bookings_start_before_end check (start_time < end_time),
  constraint bookings_exactly_one_hour check (end_time - start_time = interval '1 hour'),
  constraint bookings_opening_hours check (
    (start_time at time zone 'Africa/Casablanca') >=
      ((start_time at time zone 'Africa/Casablanca')::date + time '08:00')
    and (end_time at time zone 'Africa/Casablanca') <=
      ((start_time at time zone 'Africa/Casablanca')::date + interval '1 day')
  ),
  constraint bookings_no_overlap exclude using gist
    (tstzrange(start_time, end_time, '[)') with &&)
    where (status = 'confirmed')
);

create table if not exists public.booking_audit_logs (
  id bigint generated by default as identity primary key,
  booking_id uuid not null references public.bookings(id),
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null check (action in ('create','update','cancel')),
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz not null default now()
);

