create or replace function public.validate_booking()
returns trigger language plpgsql set search_path = '' as $$
declare
  local_start timestamp;
  local_end timestamp;
  local_day_end timestamp;
begin
  if auth.uid() is null then
    raise exception 'An authenticated moderator is required.' using errcode = '42501';
  end if;
  local_start := new.start_time at time zone 'Africa/Casablanca';
  local_end := new.end_time at time zone 'Africa/Casablanca';
  local_day_end := local_start::date + interval '1 day';
  if local_start::time < time '08:00' or local_end > local_day_end then
    raise exception 'Bookings must be between 08:00 and 00:00.';
  end if;
  if tg_op = 'INSERT' then
    new.created_by := auth.uid();
    new.updated_by := auth.uid();
  else
    if new.id is distinct from old.id
       or new.created_by is distinct from old.created_by
       or new.created_at is distinct from old.created_at then
      raise exception 'Booking identity and creation metadata are immutable.';
    end if;
    new.updated_by := auth.uid();
  end if;
  return new;
end;
$$;

create or replace function public.log_booking_change()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_action text;
begin
  if tg_op = 'INSERT' then
    insert into public.booking_audit_logs (booking_id, action, actor_id, old_data, new_data)
    values (new.id, 'create', new.created_by, null, to_jsonb(new));
    return new;
  end if;
  if (to_jsonb(old) - 'updated_at' - 'updated_by' - 'created_by')
     = (to_jsonb(new) - 'updated_at' - 'updated_by' - 'created_by') then
    return new;
  end if;
  if old.status = 'confirmed' and new.status = 'cancelled' then v_action := 'cancel';
  else v_action := 'update'; end if;
  insert into public.booking_audit_logs (booking_id, action, actor_id, old_data, new_data)
  values (new.id, v_action, new.updated_by, to_jsonb(old), to_jsonb(new));
  return new;
end;
$$;

create or replace function public.daily_summary(p_day date)
returns table (confirmed_count integer, cancelled_count integer, total_minutes integer)
language sql stable set search_path = '' as $$
  select
    (count(*) filter (where status = 'confirmed'))::integer,
    (count(*) filter (where status = 'cancelled'))::integer,
    coalesce(sum(extract(epoch from (end_time - start_time)) / 60)
      filter (where status = 'confirmed'), 0)::integer
  from public.bookings
  where start_time >= (p_day::timestamp at time zone 'Africa/Casablanca')
    and start_time < ((p_day + 1)::timestamp at time zone 'Africa/Casablanca');
$$;

